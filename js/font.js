export function textWidth(str, scale = 1) {
  return str.length ? (str.length * 4 - 1) * scale : 0;
}

// align: 'left' | 'center' | 'right'
export function drawText(ctx, str, x, y, color = '#f4f4f4', opts = {}) {
  const scale = opts.scale || 1;
  const align = opts.align || 'left';
  str = String(str).toUpperCase();
  let sx = Math.round(x);
  const w = textWidth(str, scale);
  if (align === 'center') sx = Math.round(x - w / 2);
  else if (align === 'right') sx = Math.round(x - w);
  const sy = Math.round(y);
  if (opts.shadow !== false) plot(ctx, str, sx + scale, sy + scale, opts.shadowColor || '#1a1c2c', scale);
  plot(ctx, str, sx, sy, color, scale);
}

function plot(ctx, str, x, y, color, s) {
  ctx.fillStyle = color;
  for (let i = 0; i < str.length; i++) {
    const g = G[str[i]] || G['?'];
    for (let r = 0; r < 5; r++) {
      const row = g[r];
      for (let c = 0; c < 3; c++) if (row[c] === '#') ctx.fillRect(x + (i * 4 + c) * s, y + r * s, s, s);
    }
  }
}
